export function resolveMonitorLocale(rawLocale?: string | null): MonitorLocale {
  if (rawLocale && rawLocale.toLowerCase().startsWith('zh')) return 'zh-CN';
  return 'en';
}

export function createTranslator(locale: MonitorLocale): (key: I18nKey) => string {
  const dict = locale === 'zh-CN' ? ZH_CN : EN;
  return (key: I18nKey) => dict[key] ?? EN[key];
}
