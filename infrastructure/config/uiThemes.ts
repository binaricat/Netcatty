export type UiThemeTokens = {
  background: string;
  foreground: string;
  card: string;
  cardForeground: string;
  popover: string;
  popoverForeground: string;
  primary: string;
  primaryForeground: string;
  secondary: string;
  secondaryForeground: string;
  muted: string;
  mutedForeground: string;
  accent: string;
  accentForeground: string;
  destructive: string;
  destructiveForeground: string;
  border: string;
  input: string;
  ring: string;
};

export type UiThemePreset = {
  id: string;
  name: string;
  collection?: "core";
  tokens: UiThemeTokens;
};

type UiThemeBaseTokens = Pick<
  UiThemeTokens,
  | "background"
  | "foreground"
  | "card"
  | "primary"
  | "primaryForeground"
  | "secondary"
  | "muted"
  | "mutedForeground"
  | "destructive"
  | "border"
> &
  Partial<
    Pick<
      UiThemeTokens,
      | "cardForeground"
      | "popover"
      | "popoverForeground"
      | "secondaryForeground"
      | "accent"
      | "accentForeground"
      | "destructiveForeground"
      | "input"
      | "ring"
    >
  >;

function defineUiTheme(
  id: string,
  name: string,
  t: UiThemeBaseTokens,
  collection?: "core",
): UiThemePreset {
  const preset: UiThemePreset = {
    id,
    name,
    ...(collection ? { collection } : {}),
    tokens: {
      background: t.background,
      foreground: t.foreground,
      card: t.card,
      cardForeground: t.cardForeground ?? t.foreground,
      popover: t.popover ?? t.card,
      popoverForeground: t.popoverForeground ?? t.foreground,
      primary: t.primary,
      primaryForeground: t.primaryForeground,
      secondary: t.secondary,
      secondaryForeground: t.secondaryForeground ?? t.foreground,
      muted: t.muted,
      mutedForeground: t.mutedForeground,
      accent: t.accent ?? t.primary,
      accentForeground: t.accentForeground ?? t.primaryForeground,
      destructive: t.destructive,
      destructiveForeground: t.destructiveForeground ?? t.primaryForeground,
      border: t.border,
      input: t.input ?? t.border,
      ring: t.ring ?? t.primary,
    },
  };
  return preset;
}

