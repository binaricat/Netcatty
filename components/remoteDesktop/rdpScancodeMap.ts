const CODE_MAP: Readonly<Record<string, number>> = RDP_SCANCODE;

/**
 * Convert a DOM `KeyboardEvent.code` into a PS/2 Set 1 scancode suitable for
 * IronRDP `DeviceEvent.keyPressed` / `DeviceEvent.keyReleased`.
 */
export function domCodeToRdpScancode(code: string | undefined): number | null {
  if (!code) return null;
  return CODE_MAP[code] ?? null;
}

/**
 * Returns true if the scancode carries the PS/2 Set 1 extended (`0xE0`) flag.
 */
export function isExtendedRdpScancode(scancode: number): boolean {
  return (scancode & 0xff00) === 0xe000;
}

